//! Unit test for todo_why.rs: the todo file a real `--show-cops --debug` dump names (show_cops_repo.txt; see
//! fixtures/fixtures.txt), read through a fake that gives a text written for each case.

use super::todo_why;
use std::cell::RefCell;
use std::path::{Path, PathBuf};

const REPO: &str = include_str!("fixtures/show_cops_repo.txt");
const STOCK: &str = include_str!("fixtures/show_cops_stock.txt");
const TODO: &str = "/private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml";
const TODO_TEXT: &str = "# This configuration was generated by\n# `rubocop --auto-gen-config`\n\nLint/UselessAssignment:\n  Exclude:\n    - 'a.rb'\n";

#[test]
fn todo_why_names_the_todo_file_line_and_cop() {
    let cases: [(&str, &str, &str, Option<&str>, Vec<&str>, Option<&str>); 6] = [
        ("names the cop", REPO, "Lint/UselessAssignment", Some(TODO_TEXT), vec![TODO],
            Some("rubocop's todo file /private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml names Lint/UselessAssignment on line 4: a todo file is a list of exceptions, and exceptions go in the rule file")),
        ("names the second cop of a list", REPO, "Style/StringLiterals,Lint/UselessAssignment", Some(TODO_TEXT), vec![TODO],
            Some("rubocop's todo file /private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml names Lint/UselessAssignment on line 4: a todo file is a list of exceptions, and exceptions go in the rule file")),
        ("names another cop", REPO, "Style/StringLiterals", Some(TODO_TEXT), vec![TODO], None),
        ("unreadable", REPO, "Lint/UselessAssignment", None, vec![TODO], None),
        ("a cop named only in a comment", REPO, "Style/Documentation", Some("# Style/Documentation is fine\n"), vec![TODO],
            Some("rubocop's todo file /private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml names Style/Documentation on line 1: a todo file is a list of exceptions, and exceptions go in the rule file")),
        ("no todo file read", STOCK, "Lint/UselessAssignment", Some(TODO_TEXT), vec![], None),
    ];
    let mut failed = Vec::new();
    for (name, show, check, text, want_read, want) in cases {
        let result = std::panic::catch_unwind(|| {
            let asked = RefCell::new(Vec::new());
            let read = |path: &Path| {
                asked.borrow_mut().push(path.to_path_buf());
                text.map(str::to_string)
            };
            assert_eq!(todo_why(show, check, &read).as_deref(), want, "{name}");
            assert_eq!(asked.into_inner(), want_read.iter().map(PathBuf::from).collect::<Vec<_>>(), "{name}");
        });
        if result.is_err() { failed.push(name); }
    }
    assert!(failed.is_empty(), "failed rows: {failed:?}");
}
