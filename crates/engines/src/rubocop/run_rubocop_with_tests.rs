//! Unit test for run_rubocop_with.rs: each step's stop, the commands run (their arguments and environment) and the check
//! run's count, on a fake host answering with real rubocop output (see fixtures/fixtures.txt) and a fake reader. The
//! failing probe's stderr is hand-built, in the words rubocop printed for a dead proxy.

use super::{run_rubocop_with, RUBOCOP};
use crate::host::Host;
use crate::types::{Hit, Stop};
use procio::{Cmd, Output};
use rules::{RelPath, RuleFile};
use std::cell::{Cell, RefCell};
use std::ffi::OsString;
use std::path::Path;

const OFFENSES: Answer = (1, include_bytes!("fixtures/check_offenses.json"), b"");
const REPO: Answer = (0, include_bytes!("fixtures/show_cops_repo.txt"), b"");
const STOCK: Answer = (0, include_bytes!("fixtures/show_cops_stock.txt"), b"");
const LIST: Answer = (0, include_bytes!("fixtures/list_stock.txt"), b"");
const TODO: &str = "/private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml";
const TODO_TEXT: &str = "# This configuration was generated by\n# `rubocop --auto-gen-config`\n\nLint/UselessAssignment:\n  Exclude:\n    - 'a.rb'\n";
const FIXED: [&str; 6] = ["--cache", "false", "--no-server", "--format", "json", "--ignore-disable-comments"];
/// The rule's folder, absolute on the host's platform.
const FOLDER: &str = if cfg!(windows) { "C:/w/rb" } else { "/w/rb" };

/// An exit code, stdout and stderr.
type Answer = (i32, &'static [u8], &'static [u8]);

struct Row {
    name: &'static str,
    rule: &'static str,
    dot_rubocop: Option<&'static str>,
    answers: [Answer; 4],
    want: Result<Vec<Hit>, Stop>,
    commands: Vec<Vec<String>>,
    chars: Option<usize>,
}

fn rule_text(check: &str, extra: &str) -> String {
    format!("version = 1\n[[rule]]\nid = \"r\"\nengine = \"rubocop\"\ncheck = \"{check}\"\nfix = \"f\"\n{extra}")
}

fn check_args(check: &str, config: Option<&str>) -> Vec<String> {
    let mut args: Vec<String> = FIXED.iter().map(|arg| arg.to_string()).collect();
    args.push(format!("--only={check}"));
    args.extend(config.map(|config| format!("--config={config}")));
    args.push(".".to_string());
    args
}

fn args(items: &[&str]) -> Vec<String> {
    items.iter().map(|item| item.to_string()).collect()
}

fn hit(path: &str, line: u32, col: u32, what: &str) -> Hit {
    Hit { path: RelPath::new(path), line: Some(line), col: Some(col), what: what.to_string() }
}

fn failed(stderr: &str) -> Result<Vec<Hit>, Stop> {
    Err(Stop::Failed { code: None, stderr: stderr.to_string() })
}

fn rows() -> Vec<Row> {
    let list = args(&["--list-target-files", "--force-default-config", "."]);
    let useless = "Lint/UselessAssignment";
    let in_scope = "paths = [\"example.rb\", \"lib/other.rb\"]\n";
    let options = Path::new(FOLDER).join(".rubocop");
    vec![
        Row { name: ".rubocop file", rule: "", dot_rubocop: Some("--except Lint\n"), answers: [OFFENSES, STOCK, STOCK, LIST],
            want: failed(&format!("{} gives rubocop options of its own; cctao runs rubocop with its own options only", options.display())),
            commands: vec![], chars: None },
        Row { name: "hits, with a config, probes after the check", rule: "config = \"ci/rubocop.yml\"\npaths = [\"example.rb\", \"lib/other.rb\"]\n",
            dot_rubocop: None, answers: [OFFENSES, STOCK, STOCK, LIST],
            want: Ok(vec![
                hit("example.rb", 4, 3, "Useless assignment to variable - `unused`."),
                hit("example.rb", 5, 3, "Useless assignment to variable - `quiet`."),
                hit("lib/other.rb", 4, 3, "Useless assignment to variable - `left`."),
            ]),
            commands: vec![check_args(useless, Some("ci/rubocop.yml")), args(&["--show-cops=Lint/UselessAssignment", "--debug", "--config=ci/rubocop.yml"]), list.clone()],
            chars: Some(1971) },
        Row { name: "todo file names the cop", rule: "", dot_rubocop: None, answers: [OFFENSES, REPO, STOCK, LIST],
            want: failed("rubocop's todo file /private/tmp/rubocop-fx.VqLSFl/repo/.rubocop_todo.yml names Lint/UselessAssignment on line 4: a todo file is a list of exceptions, and exceptions go in the rule file"),
            commands: vec![check_args(useless, None), args(&["--show-cops=Lint/UselessAssignment", "--debug"])], chars: Some(1971) },
        Row { name: "exclude beyond the stock one", rule: "", dot_rubocop: None, answers: [OFFENSES, REPO, STOCK, LIST],
            want: failed("the repository's rubocop config excludes \"/private/tmp/rubocop-fx.VqLSFl/repo/legacy/**/*\" from Style/StringLiterals, beyond rubocop's stock Exclude; exceptions go in the rule file"),
            commands: vec![check_args("Style/StringLiterals", None), args(&["--show-cops=Style/StringLiterals", "--debug"]), args(&["--show-cops=Style/StringLiterals", "--force-default-config"])],
            chars: Some(1971) },
        Row { name: "the stock exclude", rule: in_scope, dot_rubocop: None, answers: [OFFENSES, REPO, STOCK, LIST], want: Ok(vec![]),
            commands: vec![check_args("Style/Documentation", None), args(&["--show-cops=Style/Documentation", "--debug"]), args(&["--show-cops=Style/Documentation", "--force-default-config"]), list.clone()],
            chars: Some(1971) },
        Row { name: "a file left out", rule: "", dot_rubocop: None, answers: [OFFENSES, STOCK, STOCK, LIST],
            want: failed("the repository's rubocop config (AllCops Exclude or Include) leaves out Rakefile, a file in the rule's paths; exceptions go in the rule file"),
            commands: vec![check_args(useless, None), args(&["--show-cops=Lint/UselessAssignment", "--debug"]), list.clone()], chars: Some(1971) },
        Row { name: "no file inspected in scope", rule: "paths = [\"docs/**\"]\n", dot_rubocop: None, answers: [OFFENSES, STOCK, STOCK, LIST],
            want: Err(Stop::NoFiles { why: "no file rubocop inspects is in the rule's paths".to_string() }),
            commands: vec![check_args(useless, None), args(&["--show-cops=Lint/UselessAssignment", "--debug"]), list.clone()], chars: Some(1971) },
        Row { name: "a probe fails", rule: "", dot_rubocop: None,
            answers: [OFFENSES, (2, b"", b"Failed to open TCP connection to 127.0.0.1:9 (Connection refused)\n"), STOCK, LIST],
            want: Err(Stop::Failed { code: Some(2), stderr: "Failed to open TCP connection to 127.0.0.1:9 (Connection refused)\n".to_string() }),
            commands: vec![check_args(useless, None), args(&["--show-cops=Lint/UselessAssignment", "--debug"])], chars: Some(1971) },
        Row { name: "an unknown cop stops the check run", rule: "", dot_rubocop: None,
            answers: [(2, include_bytes!("fixtures/check_unknown.json"), include_bytes!("fixtures/check_unknown_stderr.txt")), STOCK, STOCK, LIST],
            want: Err(Stop::UnknownCheck { said: "Unrecognized cop or department: Style/NoSuchCop.".to_string() }),
            commands: vec![check_args("Style/NoSuchCop", None)], chars: Some(9875) },
    ]
}

/// The check each row runs: its own when its first command names one, else Lint/UselessAssignment.
fn check_of(row: &Row) -> String {
    row.commands.first().and_then(|args| args.iter().find_map(|arg| arg.strip_prefix("--only="))).unwrap_or("Lint/UselessAssignment").to_string()
}

#[test]
fn run_rubocop_with_runs_the_check_then_the_probes_and_stops_at_the_first_that_decides() {
    let mut failed = Vec::new();
    for row in rows() {
        let result = std::panic::catch_unwind(|| {
            let folder = Path::new(FOLDER);
            let options = folder.join(".rubocop");
            let file = RuleFile::parse(&rule_text(&check_of(&row), row.rule), folder).unwrap();
            let seen = RefCell::new(Vec::new());
            let run = |cmd: &Cmd| {
                seen.borrow_mut().push(cmd.clone());
                let has = |word: &str| cmd.args.iter().any(|arg| arg.to_string_lossy().starts_with(word));
                let at = if has("--only=") { 0 } else if has("--debug") { 1 } else if has("--list-target-files") { 3 } else { 2 };
                let (code, stdout, stderr) = row.answers[at];
                Ok(Output { code: Some(code), stdout: stdout.to_vec(), stderr: stderr.to_vec() })
            };
            let on_path = |_: &str| -> bool { panic!("run_rubocop_with looks nothing up on PATH") };
            let raw_chars = Cell::new(None);
            let host = Host { run: &run, on_path: &on_path, raw_chars: &raw_chars, base: None };
            let read = |path: &Path| match path.to_str() {
                _ if path == options => row.dot_rubocop.map(str::to_string),
                Some(TODO) => Some(TODO_TEXT.to_string()),
                other => panic!("read {other:?}"),
            };
            assert_eq!(run_rubocop_with(&read, &RUBOCOP, &file.rules[0], folder, &host), row.want, "{}", row.name);
            let commands = seen.into_inner();
            let got: Vec<Vec<String>> = commands.iter().map(|cmd| cmd.args.iter().map(|arg| arg.to_string_lossy().into_owned()).collect()).collect();
            assert_eq!(got, row.commands, "{}", row.name);
            for cmd in &commands {
                assert_eq!((cmd.program.to_str(), cmd.cwd.as_deref()), (Some("rubocop"), Some(folder)), "{}", row.name);
                assert!(cmd.env.contains(&(OsString::from("RUBOCOP_OPTS"), OsString::new())), "{}", row.name);
                assert!(cmd.env.contains(&(OsString::from("HTTPS_PROXY"), OsString::from("http://127.0.0.1:9"))), "{}", row.name);
            }
            assert_eq!(raw_chars.get(), row.chars, "{}", row.name);
        });
        if result.is_err() { failed.push(row.name); }
    }
    assert!(failed.is_empty(), "failed rows: {failed:?}");
}
